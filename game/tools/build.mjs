#!/usr/bin/env node
// tools/build.mjs — dependency-free bundler for SKYPOST.
// Inlines the ES modules of src/ in dependency order into one classic script,
// game/bundle.js, so the game also opens from file:// (Chrome blocks module
// imports there). The src/*.js files stay the readable source of truth.
//
// The transform is intentionally naive and only supports what src/ uses:
// single-line named imports (`import { a, b } from './x.js'`) and top-level
// `export function/const/class name`. Anything else fails the build loudly.

import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const srcDir = path.join(here, '..', 'src');
const outFile = path.join(here, '..', 'bundle.js');

// Topological order (every module appears after the modules it imports).
const ORDER = [
  'config.js',
  'rng.js',
  'math3.js',
  'world.js',
  'missions.js',
  'flight-model.js',
  'input.js',
  'world-renderer.js',
  'game-state.js',
  'main.js',
];

const keyOf = (file) => '__m_' + file.replace(/\.js$/, '').replace(/-/g, '_');

function bundleModule(file) {
  const code = readFileSync(path.join(srcDir, file), 'utf8');
  const exported = [];
  let out = code
    .replace(/^[ \t]*import\s*\{([^}]+)\}\s*from\s*['"]\.\/([^'"]+)['"];?[ \t]*$/gm,
      (m, names, mod) => `const {${names}} = ${keyOf(mod)};`)
    .replace(/^export\s+(async\s+function|function|class|const|let|var)\s+([A-Za-z0-9_$]+)/gm,
      (m, kind, name) => { exported.push(name); return `${kind} ${name}`; });
  if (/^[ \t]*import\s/m.test(out) || /^[ \t]*export\s/m.test(out)) {
    throw new Error(`build: unsupported import/export form left in ${file}`);
  }
  if (!exported.length && file !== 'main.js') throw new Error(`build: no exports found in ${file}`);
  return `const ${keyOf(file)} = (() => {\n${out}\n;return { ${exported.join(', ')} };\n})();\n`;
}

const banner = `// SKYPOST bundle — GENERATED by "node tools/build.mjs" from src/*.js. Do not edit by hand.\n` +
  `// Classic script (no imports) so the game runs from file:// as well as http.\n\n`;
const bundle = banner + ORDER.map(bundleModule).join('\n');
writeFileSync(outFile, bundle);
console.log(`build: wrote ${path.relative(process.cwd(), outFile)} (${bundle.length} bytes, ${ORDER.length} modules)`);
